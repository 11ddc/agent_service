# ==================== 单/多问题判断信号 ====================
# 用途：先于意图识别，用"信号计分"判断用户输入是单问题还是多问题。
# 每条是一个信号：(判定条件, 权重)。命中即向对应方向加分。
#   - SINGLE_PROBLEM_JUDGMENT  命中 → 偏向"单问题"
#   - DOUBLE_PROBLEM_JUDGMENT  命中 → 偏向"多问题"
# 建议计分（在 classifier 里实现）：
#   score = Σ命中 SINGLE 权重 − Σ命中 DOUBLE 权重
#   score >= +2 → 单问题，走老路；score <= −2 → 多问题，走拆分分支；
#   |score| < 2 → 拿不准，交给轻量模型判定（宁漏勿错，不下硬结论）。
# 信号写法：正则字符串可直接 re.search；"问号数量/字数/分号"等结构类信号
# 用中文描述（在代码里判断），两者用注释里的 ── 分组区分。

# 单问题信号（命中即向"单"加分）
SINGLE_PROBLEM_JUDGMENT = [
    # ── 1. 结构类强信号：只有一个问号、没有连接词 ──
    ("问号数量 == 1，且不含任何连接词", 3),
    #   "怎么申请退货？" / "保修期是多久？" —— 你提到的核心场景
    ("问号数量 == 0，且总字数 <= 25", 2),
    #   "我要退货" / "帮我查物流" —— 无问号的陈述式短需求
    ("不含分号；且不含换行", 1),
    # ── 2. 语义上是一个问题的强信号 ──
    (r"还是|或者", 3),
    #   "你是想退货还是换货？" —— 选择疑问句，二选一，绝不能拆
    (r"区别|不同|对比|哪个更|谁更", 2),
    #   "退货和换货有什么区别？" —— 对比疑问句，一个问句比较两个对象
    (r"吗$|是否|能不能|可不可以|行不行", 1),
    #   "可以七天无理由退货吗？" —— 是非问句
    (r"还有(别的|其他|其它).{0,8}吗", 2),
    #   "还有别的退款方式吗？" —— 陷阱信号："还有…吗"其实是单问，抵消"还有"的多信号
    # ── 3. 弱信号：问法单一 / 极短句 ──
    (r"^(怎么|如何|为什么|多少|几|什么)", 1),
    #   "怎么退货" / "如何申请售后" —— 疑问词开头，通常是单问
    ("总字数 <= 15", 1),
    #   "你好" / "我要投诉" / "退货" —— 极短句
]

